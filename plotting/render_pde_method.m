function metadata = render_pde_method(input_file, output_stem)
% Render the saved truth and confidence bounds without changing their values.
data = load(input_file);
required = {'node','elem','truth','lower','upper','z_limits','color_limits','method'};
assert(all(isfield(data,required)), 'The plot input is missing required fields.');
method = char(string(data.method));
view_angles = [-37.5 25];
appearance = struct('z_aspect',1.35,'truth_edge_color','interp', ...
    'color_limits',[0 .08]);

validateattributes(data.node,{'numeric'},{'real','finite','2d','ncols',2});
validateattributes(data.elem,{'numeric'},{'real','finite','2d','ncols',3,'integer','positive'});
n = size(data.node,1);
assert(all(data.elem(:)<=n), 'A triangle refers to an unavailable node.');
data.truth = data.truth(:);
assert(numel(data.truth)==n && isequal(size(data.lower),[n 2]) && ...
    isequal(size(data.upper),[n 2]), 'Unexpected truth or interval dimensions.');
assert(all(isfinite([data.truth; data.lower(:); data.upper(:)])), ...
    'All plotted heights must be finite.');
assert(all(data.upper(:)>data.lower(:)), 'Invalid interval endpoints.');
validateattributes(data.z_limits,{'numeric'},{'real','finite','numel',2});
assert(data.z_limits(2)>data.z_limits(1), 'Invalid vertical limits.');
assert(isequal(data.color_limits(:)',appearance.color_limits), ...
    'The batch must use the selected common color limits [0, 0.08].');
all_heights = [data.truth; data.lower(:); data.upper(:)];
tolerance = 64*eps(max(1,max(abs(all_heights))));
assert(min(all_heights)>=data.z_limits(1)-tolerance && ...
    max(all_heights)<=data.z_limits(2)+tolerance, ...
    'The shared vertical range would clip truth or confidence bounds.');
boundary_edges = freeBoundary(triangulation(double(data.elem),double(data.node)));
boundary_degree = accumarray(boundary_edges(:),1,[n 1]);
assert(~isempty(boundary_edges) && all(boundary_degree(boundary_degree>0)==2), ...
    'Expected a closed source-region boundary.');

metadata = struct('method',method,'input_file',input_file, ...
    'view_angles',view_angles,'projection','orthographic', ...
    'appearance',appearance,'plot_box_aspect_ratio',[1 1 1.35], ...
    'z_limits',data.z_limits(:)','color_limits',appearance.color_limits, ...
    'panel_order',{{'debiased','original'}},'side_walls',true, ...
    'side_alpha',.22,'colormap','MATLAB jet(256), linear mapping', ...
    'interval_endpoints_modified',false,'true_vertex_heights_modified',false, ...
    'page_points',[653 303],'png_dpi',240,'pdf_dpi',600, ...
    'pdf_export','MATLAB OpenGL print -dpdf -r600');
for field = {'outer','run_id','variant_id','transform','q_debiased','q_original'}
    name = field{1};
    if isfield(data,name), metadata.(name) = data.(name); end
end

width = 653/72;
height = 303/72;
fig = figure('Visible','off','Name',method,'NumberTitle','off','Color','w', ...
    'Units','inches','Position',[1 1 width height],'Renderer','opengl', ...
    'PaperUnits','inches','PaperSize',[width height], ...
    'PaperPosition',[0 0 width height],'InvertHardcopy','off', ...
    'UserData',metadata);
cleanup = onCleanup(@() close(fig));
set(fig,'DefaultAxesFontName','Helvetica','DefaultAxesFontSize',8, ...
    'DefaultTextFontName','Times New Roman','DefaultTextFontSize',9);
colormap(fig,jet(256));
positions = [.0147 .0495 .4537 .9139; .4937 .0495 .4537 .9139];
panel_titles = {'Debiased estimator', ...
                'Original estimator'};
axes_handles = gobjects(1,2);
tick_step = .02;
z_ticks = (ceil(data.z_limits(1)/tick_step):floor(data.z_limits(2)/tick_step))*tick_step;
z_ticks(abs(z_ticks)<eps) = 0;
for panel = 1:2
    ax = axes(fig,'Units','normalized','Position',positions(panel,:), ...
        'Tag',sprintf('confidence_panel_%d',panel));
    axes_handles(panel) = ax;
    hold(ax,'on');
    upper_mesh = trimesh(data.elem,data.node(:,1),data.node(:,2),data.upper(:,panel), ...
        'Parent',ax,'FaceAlpha',0,'EdgeColor','k','LineWidth',.1,'Tag','upper_bound');
    lower_mesh = trimesh(data.elem,data.node(:,1),data.node(:,2),data.lower(:,panel), ...
        'Parent',ax,'FaceAlpha',0,'EdgeColor','k','LineWidth',.1,'Tag','lower_bound');
    truth_surface = trisurf(data.elem,data.node(:,1),data.node(:,2),data.truth, ...
        'Parent',ax,'FaceAlpha',1,'FaceColor','interp', ...
        'EdgeColor',appearance.truth_edge_color,'LineWidth',.1,'Tag','true_solution');
    assert(isequal(truth_surface.Vertices(:,3),data.truth));
    assert(isequal(upper_mesh.Vertices(:,3),data.upper(:,panel)));
    assert(isequal(lower_mesh.Vertices(:,3),data.lower(:,panel)));
    wall_vertices = [data.node data.lower(:,panel); data.node data.upper(:,panel)];
    wall_faces = [boundary_edges boundary_edges(:,[2 1])+n];
    patch(ax,'Vertices',wall_vertices,'Faces',wall_faces, ...
        'FaceColor',[.58 .68 .78],'FaceAlpha',.22, ...
        'EdgeColor',[.15 .20 .25],'EdgeAlpha',.65, ...
        'LineWidth',.25,'FaceLighting','none','Tag','boundary_walls');
    view(ax,view_angles(1),view_angles(2));
    axis(ax,[-.5 .5 -.5 .5 data.z_limits(:)']);
    caxis(ax,appearance.color_limits);
    set(ax,'Box','off','XGrid','off','YGrid','off','ZGrid','off', ...
        'Color','none','FontName','Helvetica','FontSize',8, ...
        'LineWidth',.5,'TickDir','out','XTick',[-.5 0 .5], ...
        'YTick',[-.5 0 .5],'ZTick',z_ticks, ...
        'Projection','orthographic','PlotBoxAspectRatio',[1 1 appearance.z_aspect]);
    xlabel(ax,'$x_1$','Interpreter','latex','FontSize',9);
    ylabel(ax,'$x_2$','Interpreter','latex','FontSize',9);
    zlabel(ax,'');
    annotation(fig,'textbox',[positions(panel,1) .938 positions(panel,3) .05], ...
        'String',panel_titles{panel},'Interpreter','latex', ...
        'FontSize',10,'HorizontalAlignment','center','VerticalAlignment','middle', ...
        'LineStyle','none','Margin',0);
    hold(ax,'off');
end
bar = colorbar(axes_handles(2),'Position',[.939 .03 .0245 .94]);
set(bar,'FontName','Helvetica','FontSize',7.2,'LineWidth',.5,'TickDirection','out');
for panel = 1:2, set(axes_handles(panel),'Position',positions(panel,:)); end
label_layer = axes(fig,'Units','normalized','Position',[0 0 1 1], ...
    'Visible','off','Color','none','XLim',[0 1],'YLim',[0 1]);
for left = [.008 .487]
    text(label_layer,left,.53,'$[M_0^{1/2} f](x_1,x_2)$', ...
        'Interpreter','latex','FontSize',8,'Rotation',90, ...
        'HorizontalAlignment','center','VerticalAlignment','middle');
end

drawnow;
print(fig,[output_stem '.png'],'-dpng','-r240','-opengl');
print(fig,[output_stem '.pdf'],'-dpdf','-r600','-opengl');
end
